// opsByGroup returns the registered operations of each group in the order of
// groups, keeping registration order within a group.
func opsByGroup() [][]*Op {
	out := make([][]*Op, len(groups))
	for i, g := range groups {
		for _, name := range g.Lead {
			if op := findOp(g.Name + "." + name); op != nil {
				out[i] = append(out[i], op)
			}
		}
		for _, op := range registry {
			if op.group() == g.Name && !slices.Contains(g.Lead, op.short()) {
				out[i] = append(out[i], op)
			}
		}
	}
	return out
}

func firstSentence(s string) string {
	if i := strings.IndexAny(s, ".:("); i > 0 {
		return strings.TrimSpace(s[:i])
	}
	return s
}

// sentence ends s with a full stop unless it already ends with punctuation.
func sentence(s string) string {
	s = strings.TrimSpace(s)
	end := strings.TrimRight(s, ")")
	if s == "" || end != "" && strings.ContainsAny(end[len(end)-1:], ".!?") {
		return s
	}
	return s + "."
}

// mdText makes free text safe inside a Markdown table cell or paragraph.
func mdText(s string) string {
	return strings.NewReplacer("|", `\|`, "<", "&lt;", ">", "&gt;", "\n", " ").Replace(s)
}

func flagName(p Param) string { return "--" + strings.ReplaceAll(p.Name, "_", "-") }

func paramNotes(p Param) []string {
	var n []string
	if p.Required {
		n = append(n, "**Required.**")
	}
	if p.Default != nil {
		n = append(n, fmt.Sprintf("Default `%v`.", p.Default))
	}
	if len(p.Enum) > 0 {
		n = append(n, "One of `"+strings.Join(p.Enum, "`, `")+"`.")
	}
	if p.Secret {
		n = append(n, "Secret: falls back to `IDPDBG_"+strings.ToUpper(p.Name)+"`, redacted in traces.")
	}
	if p.File {
		n = append(n, "CLI: `@path` reads a file, `-` reads stdin.")
	}
	if p.Path {
		n = append(n, "May be a file path (CLI or profile only).")
	}
	if p.Explicit {
		n = append(n, "Over MCP it must be passed in the call, never taken from a profile or the environment.")
	}
	return n
}

func paramTable(b *bytes.Buffer, ps []Param) {
	b.WriteString("| Parameter | Type | Description |\n|---|---|---|\n")
	for _, p := range ps {
		desc := mdText(sentence(p.Desc))
		if n := paramNotes(p); len(n) > 0 {
			desc += " " + mdText(strings.Join(n, " "))
		}
		fmt.Fprintf(b, "| `%s` | %s | %s |\n", flagName(p), p.Type, desc)
	}
}

const generatedNote = "<!-- Generated by `idpdbg docs` from the operation definitions. Do not edit; run `go run . docs` after changing an operation. -->\n\n"

// referenceDocs renders the command reference: an index and one page per group.
func referenceDocs() map[string][]byte {
	files := map[string][]byte{}
	byGroup := opsByGroup()

	var idx bytes.Buffer
	idx.WriteString(generatedNote)
	idx.WriteString("# idpdbg command reference\n\n")
	idx.WriteString("Every operation runs as `idpdbg <group> <operation> [--param value ...]` and as the MCP tool `<group>_<operation>`, ")
	idx.WriteString("with the same parameters (`--client-id` on the command line is `client_id` over MCP). ")
	idx.WriteString("Each prints a JSON result with a `checks` list of findings (`pass`, `fail`, `warn`, `info`). ")
	idx.WriteString("Exit status: 0 ok, 1 error, 2 when a check failed.\n\n")
	idx.WriteString("| Group | Operations |\n|---|---|\n")
	for i, g := range groups {
		var names []string
		for _, op := range byGroup[i] {
			names = append(names, fmt.Sprintf("[`%s`](%s.md#%s)", op.short(), g.Name, anchor(op)))
		}
		fmt.Fprintf(&idx, "| [%s](%s.md) — %s | %s |\n", g.Name, g.Name, mdText(g.Title), strings.Join(names, ", "))
	}

	idx.WriteString("\n## Common parameters\n\nEvery operation also takes these.\n\n")
	paramTable(&idx, commonParams)

	idx.WriteString("\n## Secrets\n\nA secret parameter falls back to the environment variable `IDPDBG_` plus its name in capitals, ")
	idx.WriteString("so it stays out of shell history and MCP tool arguments. These are the secret parameters:\n\n")
	seen := map[string]bool{}
	var secrets []string
	for _, ops := range byGroup {
		for _, op := range ops {
			for _, p := range op.Params {
				if p.Secret && !seen[p.Name] {
					seen[p.Name] = true
					secrets = append(secrets, fmt.Sprintf("- `%s` → `IDPDBG_%s`", flagName(p), strings.ToUpper(p.Name)))
				}
			}
		}
	}
	idx.WriteString(strings.Join(secrets, "\n") + "\n")

	idx.WriteString("\n## Operations that change data\n\nThey change state at the remote system (or, for the `card` writes, on the card) and are annotated as not read-only over MCP; confirm before running them against a real system.\n\n")
	idx.WriteString(opList(byGroup, func(op *Op) bool { return op.Mutating }))
	idx.WriteString("\n## Operations that open a browser\n\nThey open the browser on the machine running idpdbg and wait for a person to finish.\n\n")
	idx.WriteString(opList(byGroup, func(op *Op) bool { return op.Browser }))
	files["README.md"] = idx.Bytes()

	for i, g := range groups {
		var b bytes.Buffer
		b.WriteString(generatedNote)
		fmt.Fprintf(&b, "# %s — %s\n\n[All groups](README.md)\n", g.Name, mdText(g.Title))
		more := "Plus the [common parameters](README.md#common-parameters).\n"
		if gp := groupParams[g.Name]; len(gp) > 0 {
			fmt.Fprintf(&b, "\n## Every %s operation\n\nEvery operation in this group also takes these.\n\n", g.Name)
			paramTable(&b, gp)
			more = fmt.Sprintf("Plus the parameters [every %s operation](#every-%s-operation) takes and the [common parameters](README.md#common-parameters).\n", g.Name, g.Name)
		}
		for _, op := range byGroup[i] {
			fmt.Fprintf(&b, "\n## %s %s\n\n%s\n\n", g.Name, op.short(), mdText(op.Summary))
			fmt.Fprintf(&b, "MCP tool: `%s`.", op.tool())
			if op.Mutating {
				b.WriteString(" **Changes data at the remote system.**")
			}
			if op.Browser {
				b.WriteString(" Opens a browser and waits for a person.")
			}
			b.WriteString("\n\n")
			if len(op.Params) > 0 {
				paramTable(&b, op.Params)
				b.WriteString("\n")
			}
			b.WriteString(more)
		}
		files[g.Name+".md"] = b.Bytes()
	}
	return files
}

// anchor is the GitHub anchor of the "## group operation" heading.
func anchor(op *Op) string { return op.group() + "-" + op.short() }

func opList(byGroup [][]*Op, keep func(*Op) bool) string {
	var lines []string
	for i, ops := range byGroup {
		for _, op := range ops {
			if keep(op) {
				lines = append(lines, fmt.Sprintf("- [`%s %s`](%s.md#%s) (`%s`)", op.group(), op.short(), groups[i].Name, anchor(op), op.tool()))
			}
		}
	}
	return strings.Join(lines, "\n") + "\n"
}

// writeReference writes the reference into dir, removing pages of groups
// that no longer exist.
//
// It only ever replaces or removes files it generated itself (they start
// with generatedNote), refuses to overwrite anything else, and never writes
// through a symbolic link, so pointing it at a directory with other
// Markdown files is safe.
func writeReference(dir string) ([]string, error) {
	files := referenceDocs()
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return nil, err
	}
	generated := func(path string) (bool, error) {
		fi, err := os.Lstat(path)
		if os.IsNotExist(err) {
			return false, nil
		}
		if err != nil {
			return false, err
		}
		if !fi.Mode().IsRegular() {
			return false, fmt.Errorf("%s is not a regular file (a link?); not touching it", path)
		}
		b, err := os.ReadFile(path)
		if err != nil {
			return false, err
		}
		if !bytes.HasPrefix(b, []byte(generatedNote)) {
			return false, fmt.Errorf("%s exists and was not generated by idpdbg docs; not overwriting it", path)
		}
		return true, nil
	}
	for _, name := range sortedKeys(files) {
		if _, err := generated(filepath.Join(dir, name)); err != nil {
			return nil, err
		}
	}
	// Pages of groups that no longer exist: remove only generated ones.
	old, _ := filepath.Glob(filepath.Join(dir, "*.md"))
	for _, f := range old {
		if _, keep := files[filepath.Base(f)]; keep {
			continue
		}
		if ok, err := generated(f); err == nil && ok {
			if err := os.Remove(f); err != nil {
				return nil, err
			}
		}
	}
	var written []string
	for _, name := range sortedKeys(files) {
		if err := os.WriteFile(filepath.Join(dir, name), files[name], 0o644); err != nil {
			return nil, err
		}
		written = append(written, filepath.Join(dir, name))
	}
	return written, nil
}
